import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

export const projectRoot = fileURLToPath(new URL('../', import.meta.url));

/**
 * Keep watch, production, and deployment bundles compatible with Obsidian.
 * @param options.production Whether to minify and omit development source maps.
 * @param options.outfile Bundle destination; defaults to the release artifact at the project root.
 */
export function buildOptions({
	production = false,
	outfile = join(projectRoot, 'main.js'),
} = {}) {
	return {
		absWorkingDir: projectRoot,
		entryPoints: ['src/main.ts'],
		bundle: true,
		external: ['obsidian'],
		platform: 'browser',
		format: 'cjs',
		target: 'es2021',
		logLevel: 'info',
		sourcemap: production ? false : 'inline',
		treeShaking: true,
		minify: production,
		outfile,
		banner: { js: '/* Generated by esbuild. See src/ for the source. */' },
	};
}
